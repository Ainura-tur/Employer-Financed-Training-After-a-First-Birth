# 1. THE CROSS-PARTIAL PROFILE
#
# The cross-partial has a closed form in the quadratic specification,
# b1 + 2*b2*(e - centre), where b1 is the coefficient on educ_c*exp_c and b2
# that on educ_c*exp_c^2 and centre is that sex's own mean experience. Each sex
# is evaluated at the SAME e, which is the whole point: the linear estimate is
# each sex's cross-partial at its own mean, 17.2 years against 15.7, so
# differencing the linear estimates compares two points on a curve.
# =============================================================================
xpartial <- function(m, centre, e) {
  b1 <- tryCatch(unname(stats::coef(m)[["educ_exp_c"]]),  error = function(x) NA_real_)
  b2 <- tryCatch(unname(stats::coef(m)[["educ_exp_c2"]]), error = function(x) NA_real_)
  if (!is.finite(b1) || !is.finite(b2)) return(NA_real_)
  b1 + 2 * b2 * (e - centre)
}

# THE TABLE HAD NO UNCERTAINTY IN IT, and a referee read six point estimates
# changing sign and asked, correctly, what could be concluded from them. The
# answer turned out to be almost nothing: the largest |t| on the difference is
# 0.47 and the minimum detectable effect runs six to thirty times the point
# differences. That verdict is only available with the columns below.
#
# IT IS A DELTA METHOD, NOT A NEW DESIGN. The cross-partial is
# b1 + 2 b2 (e - centre), a linear combination of two estimated coefficients,
# so its variance is V11 + 4 d^2 V22 + 4 d V12 with d = e - centre. Nothing is
# re-estimated; the covariance sat in the fit all along and was never read.
xpartial_se <- function(m, centre, e) {
  V <- tryCatch(stats::vcov(m), error = function(x) NULL)
  if (is.null(V) || !all(c("educ_exp_c", "educ_exp_c2") %in% rownames(V)))
    return(NA_real_)
  d <- e - centre
  v <- V["educ_exp_c", "educ_exp_c"] + 4 * d^2 * V["educ_exp_c2", "educ_exp_c2"] +
    4 * d * V["educ_exp_c", "educ_exp_c2"]
  if (!is.finite(v) || v < 0) NA_real_ else sqrt(v)
}

# The two arms are fitted on disjoint persons, the paper's standing convention
# for a sex difference, so the variances add.
xpartial_gap_se <- function(mm, cm, mw, cw, e) {
  sm <- xpartial_se(mm, cm, e); sw <- xpartial_se(mw, cw, e)
  if (!is.finite(sm) || !is.finite(sw)) NA_real_ else sqrt(sm^2 + sw^2)
}


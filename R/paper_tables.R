# NEITHER IS DERIVABLE FROM `d`, so neither is invented. The extract is
# the panel before the age-experience screen and the roster is built in
# the design stage, so both are read from whatever holds them and the
# macro is simply absent when nothing does. Section 6 lists what did not
# generate, and an absent macro fails at compile time with a name.
.reg <- function(key) {
  if (!exists("td_has", mode = "function") ||
      !exists("td_get", mode = "function")) return(NULL)
  if (!isTRUE(tryCatch(td_has(key), error = function(e) FALSE))) return(NULL)
  o <- tryCatch(td_get(key), error = function(e) NULL)
  if (is.data.frame(o)) o else NULL
}


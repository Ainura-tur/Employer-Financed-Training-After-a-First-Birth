build_ledger_table <- function() {
  led <- read_csv_if("training_ledger.csv")
  if (is.null(led) || !all(c("tag", "n", "se", "mde", "status") %in% names(led))) {
    cat("  *** training_ledger.csv absent, so tab_mde_ledger is carried.\n")
    return(NULL)
  }
  # The verdict is a property of the estimate and the status a property of the
  # design. Printing them in one column headed Status is what let a reader
  # take "limited" for something fixed before unblinding; they are separated.
  led$panel <- sub("^(T[0-9]+[a-z]?)_.*$", "\\1", led$tag)
  out <- character(0)
  # THE PANEL LIST IS DERIVED, NOT TYPED. A first version iterated over
  # LEDGER_PANELS and emitted 29 of the ledger's 40 rows, dropping T12,
  # T2c, T3c, T4c and T5b because they were not in the list. Silently: the
  # table would have looked complete and been eleven rows short, which is
  # the failure this file keeps finding elsewhere and had just reproduced.
  #
  # So the ledger decides which panels exist and LEDGER_PANELS supplies a
  # readable name where it has one. A panel with no name prints under its
  # tag rather than vanishing, and the row count is asserted below.
  # THE TABLE IS THE PRE-ANALYSIS LEDGER, NOT THE WHOLE LEDGER. Its caption
  # says "pre-committed status" and the status paragraph beside it says one
  # post-hoc arm is tabulated and no other. The file has grown to 90 rows
  # since 03c and 04financing_space started contributing, and emitting all of
  # them put 24 rows of financing-space state names into a table about
  # pre-commitment, ran it off the page and under the footer.
  #
  # So the post-hoc and discovery-derived rows are held back and counted. They
  # are not lost: they are in the csv, and the appendix arms table shows them.
  # A row whose status was decided AFTER seeing an estimate does not belong in
  # a table whose whole claim is that status was decided before.
  # "not identified" JOINS THE RULE ON ITS OWN MERITS, not as a patch for a
  # status string. A specification the estimating module declares structurally
  # unidentified has no business in a table of pre-committed designs whatever
  # else its status says, and reading the rule off the substantive claim
  # rather than off the label means the table is right even when a row was
  # written hours earlier by a script that has since been edited. On this
  # ledger the phrase appears in exactly one status, the five within-person
  # experience arms, and 03c marks them post-hoc as well.
  .posthoc <- grepl("post-hoc|discovery-derived|power only|not identified",
                    led$status)

  # ONE NAMED EXCEPTION, BECAUSE THE TEXT NAMES IT. Section 5 says: "One arm
  # designated after unblinding is tabulated there as well, the pre-birth
  # full-time restriction, because the text quotes its minimum detectable
  # effect against the objection it answers; its status column reads post-hoc
  # and no other row in the table does." The blanket rule dropped it, so the
  # sentence described a row the table did not contain. Keeping it by tag
  # rather than by loosening the rule means the exception stays visible here
  # and cannot be inherited by the next post-hoc arm someone adds.
  .keep_named <- led$tag %in% c("T4c_pre_birth_ft")
  .posthoc <- .posthoc & !.keep_named

  # ONE NAMED EXCLUSION, for the same sentence read forwards. The dollar
  # valuation is listed among the arms that are NOT tabulated, but
  # T11_inv_now carries "diagnostic (contamination only)", which the rule
  # above does not match, so a single dollar row reached the page with an MDE
  # of 338 in a column of training percentages. The panel is excluded by name
  # rather than by restating its status, which belongs to 04 and describes
  # what the arm is, not where it prints.
  .drop_named <- grepl("^T11_", led$tag)
  .posthoc <- .posthoc | .drop_named

  if (any(.posthoc)) {
    cat("  ", sum(.posthoc), " post-hoc, discovery-derived or dollar row(s)\n",
        "  held back from the pre-commitment table; they remain in the csv\n",
        "  and in the appendix arms table.\n", sep = "")
    if (any(.keep_named))
      cat("  kept by name, as Section 5 states: ",
          paste(led$tag[.keep_named], collapse = ", "), "\n", sep = "")
    led <- led[!.posthoc, , drop = FALSE]
  }
  # The sentence claims exactly one post-hoc row is tabulated. Assert it here
  # rather than leave it to a reader comparing a paragraph with a page.
  .np <- sum(grepl("post-hoc", led$status))
  if (.np != 1L)
    cat("  *** ", .np, " post-hoc row(s) survive into tab_mde_ledger, and\n",
        "      Section 5 says exactly one does. Fix the text or the rule.\n",
        sep = "")

  # T10 SORTS BEFORE T2 AS A STRING. Numerically, with the letter suffix as a
  # tie-break, so T2 then T2c then T3.
  .pn <- as.integer(sub("^T([0-9]+).*$", "\\1", unique(led$panel)))
  .ps <- sub("^T[0-9]+", "", unique(led$panel))
  .panels <- unique(led$panel)[order(.pn, .ps)]
  .n_dag <- 0L
  for (p in .panels) {
    rows <- led[led$panel == p, , drop = FALSE]
    if (!nrow(rows)) next
    # NEVER PUT AN R NAME IN A TYPESET TABLE. The fallback used to read
    # "(no title in LEDGER_PANELS)", which has an underscore, so LaTeX
    # halted at "Missing $ inserted" on the first panel that lacked a
    # title. Escaping it would have fixed the build and left a referee
    # reading the name of a variable in this script. The tag alone is what
    # belongs on the page; the log says which titles are missing.
    .nm <- if (!is.null(LEDGER_PANELS[[p]])) LEDGER_PANELS[[p]] else
      paste0(p, ".")
    .nm <- gsub("([&%$#_{}])", "\\\\\\1", .nm)
    out <- c(out, sprintf("\\multicolumn{6}{l}{\\emph{%s}} \\\\", .nm))
    for (k in seq_len(nrow(rows))) {
      r <- rows[k, ]
      st <- as.character(r$status)
      vd <- if ("verdict" %in% names(r) && !is.na(r$verdict) &&
                identical(toupper(as.character(r$verdict)), "LIMITED"))
        "limited" else ""
      # v38. THE DAGGER THE TEXT PROMISES. The paragraph before this table
      # says the rows graded limited against the pooled base but clearing
      # women's own pre-birth base carry a dagger, and the table note
      # explains the mark, but no row was ever given one. The ledger records
      # the second grading in verdict_f, so the mark is read from it rather
      # than typed against four names.
      if (nzchar(vd) && "verdict_f" %in% names(r) && !is.na(r$verdict_f) &&
          identical(toupper(as.character(r$verdict_f)), "OK")) {
        vd <- paste0(vd, "$^{\\dagger}$")
        .n_dag <- .n_dag + 1L
      }
      # THE LEDGER HAS A label COLUMN AND THE BUILDER IGNORED IT, so the
      # table printed pe\_emp\_wp\_mixed\_nofee where the manuscript has
      # always carried prose. The label is what the module wrote for a
      # human; the tag is a key. Fall back to the tag only where a label
      # is missing, and escape either way.
      .arm <- if ("label" %in% names(r) && !is.na(r$label) &&
                  nzchar(as.character(r$label)))
        as.character(r$label) else sub("^T[0-9]+[a-z]?_", "", r$tag)
      # THE MODULE'S LABEL IS HALF PROSE AND HALF COLUMN NAME. It writes
      # "employer-funded, employed or on parental leave", which is what a
      # reader wants, and "jttpeot_any employed only", which is not. The
      # outcome names are substituted rather than the whole label mapped:
      # four entries fix most rows, and an unlisted one degrades to an
      # escaped column name instead of disappearing.
      # v-ledger-labels: prose by tag where LEDGER_ARM_LABELS has it.
      if (r$tag %in% names(LEDGER_ARM_LABELS)) .arm <- LEDGER_ARM_LABELS[[r$tag]]
      for (.k in seq_along(OUTCOME_PROSE))
        .arm <- sub(names(OUTCOME_PROSE)[.k], OUTCOME_PROSE[[.k]], .arm, fixed = TRUE)
      # v38. ONE TERM. The module writes "employer-funded"; the paper says
      # employer-financed everywhere else and undertakes to use the one term,
      # so eight rows of this table were the only place it varied.
      .arm <- gsub("employer-funded", "employer-financed", .arm, fixed = TRUE)
      .arm <- gsub("([&%$#_{}])", "\\\\\\1", .arm)
      out <- c(out, row_tex(
        "", .arm,
        format(as.numeric(r$n), big.mark = ","),
        formatC(as.numeric(r$se),  format = "f", digits = 4),
        formatC(as.numeric(r$mde), format = "f", digits = 4),
        trimws(paste(st, vd, sep = if (nzchar(vd)) ", " else ""))))
    }
  }
  # v38. The paragraph before the table names four daggered rows: the
  # couple-by-wave arm, its separate-effects companion, and the two
  # anticipation arms. Say so when the ledger gives a different count.
  cat("  rows given the dagger (limited on the pooled base, OK on women's): ",
      .n_dag, "\n", sep = "")
  if (.n_dag != 4L)
    cat("  *** the paragraph before the ledger table names four such rows and\n",
        "      the ledger gives ", .n_dag, ". Fix the text, or check verdict_f.\n",
        sep = "")
  # EVERY LEDGER ROW REACHES THE TABLE, asserted rather than assumed.
  .emitted <- sum(!grepl("multicolumn", out))
  cat("  ledger table rebuilt from training_ledger.csv: ", .emitted, " of ",
      nrow(led), " rows across ", length(.panels), " panels.\n", sep = "")
  if (.emitted != nrow(led))
    cat("  *** ", nrow(led) - .emitted, " ledger row(s) did not reach the\n",
        "      table. The tag pattern failed on them, so the table is\n",
        "      short and looks complete.\n", sep = "")
  .miss <- setdiff(.panels, names(LEDGER_PANELS))
  if (length(.miss))
    cat("  panels with no title in LEDGER_PANELS, printed under their tag: ",
        paste(.miss, collapse = ", "), "\n", sep = "")
  out
}


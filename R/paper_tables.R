.fit_profile <- function(dat, horizons) {
  if (!requireNamespace("fixest", quietly = TRUE)) {
    cat("  fixest unavailable, so the profile cannot be fitted here.\n"); return(NULL)
  }
  # COLUMNS ARE RESOLVED, NOT ASSUMED, and hard-coding one name is why this
  # table sat at its 4 September version through three later builds. The
  # requirement was "ln_hourly_wage"; the pipeline calls it
  # ln_hourly_wage_real in 75 places against 8 for the plain name, and
  # RUN_FIGURES_PAPER.R has resolved it as need("ln_hourly_wage_real",
  # "ln_hourly_wage") all along. So .fit_profile returned NULL, build_profile
  # returned placeholders, and write_body correctly refused to overwrite real
  # values with them. Three guards behaved perfectly and the outcome was a
  # fragment two days stale that nothing complained about.
  #
  # THE REAL SERIES IS PREFERRED, deliberately. Appendix A.1's wage equations
  # are in real terms and the master's A5(iii) fits the same, so taking the
  # nominal series here would put a different profile in the table from the
  # one the cross-check below compares against. Which name resolved is
  # printed, because real against nominal is not a cosmetic difference.
  .pick <- function(...) { cand <- c(...); hit <- intersect(cand, names(dat))
                           if (length(hit)) hit[1] else NA_character_ }
  .v <- c(lnw  = .pick("ln_hourly_wage_real", "ln_hourly_wage"),
          educ = .pick("educ_years", "education", "educ"),
          exp  = .pick("experience_years", "exp_cal_obs"),
          fem  = .pick("female"), pid = .pick("person_id"), wv = .pick("wave"))
  if (any(is.na(.v))) {
    cat("  the profile cannot be fitted: no column resolved for ",
        paste(names(.v)[is.na(.v)], collapse = ", "), ".\n", sep = "")
    cat("    the panel does hold: ",
        paste(head(grep("wage|educ|experience", names(dat), value = TRUE), 8),
              collapse = ", "), "\n", sep = "")
    return(NULL)
  }
  cat("  profile columns: wage = ", .v[["lnw"]], ", education = ", .v[["educ"]],
      ", experience = ", .v[["exp"]], "\n", sep = "")
  dat$.lnw <- dat[[.v[["lnw"]]]]
  dat$educ_years <- dat[[.v[["educ"]]]]
  dat$experience_years <- dat[[.v[["exp"]]]]
  w <- dat[!is.na(dat$.lnw) & !is.na(dat$educ_years) &
             !is.na(dat$experience_years) & !is.na(dat$female), ]
  if ("in_wage_sample" %in% names(w)) w <- w[w$in_wage_sample == 1, ]

  # Appendix A.1's control set, each resolved rather than assumed. A control
  # that is absent is dropped and named, because a profile fitted on a
  # different control set is a different profile.
  ctrl <- Filter(Negate(is.na), c(
    "experience_years",
    intersect(c("age_sq", "age2"), names(w))[1],
    intersect(c("married", "partnered"), names(w))[1]))
  if (length(ctrl) < 3)
    cat("  profile controls unavailable and omitted: ",
        paste(setdiff(c("age squared", "marital status"), ctrl), collapse = ", "),
        ". Not the appendix's specification.\n", sep = "")

  out <- lapply(c(0, 1), function(sx) {
    dd <- w[w$female == sx, ]
    eb <- mean(dd$experience_years); db <- mean(dd$educ_years)
    dd$.ec <- dd$educ_years - db
    dd$.xc <- dd$experience_years - eb
    f <- stats::as.formula(paste0(
      ".lnw ~ I(.ec * .xc) + I(.ec * .xc^2) + ",
      paste(ctrl, collapse = " + "), " | person_id + wave"))
    m <- fixest::feols(f, data = dd, cluster = ~person_id)
    b <- stats::coef(m); V <- stats::vcov(m)
    i1 <- grep("\\.ec \\* \\.xc\\)", names(b))[1]
    i2 <- grep("\\.xc\\^2", names(b))[1]
    dv <- horizons - eb
    data.frame(
      e   = horizons,
      est = 100 * (b[i1] + 2 * b[i2] * dv),
      se  = 100 * sqrt(pmax(0, V[i1, i1] + 4 * dv^2 * V[i2, i2] +
                              4 * dv * V[i1, i2])))
  })
  data.frame(e = horizons,
             est_men = out[[1]]$est, se_men = out[[1]]$se,
             est_women = out[[2]]$est, se_women = out[[2]]$se)
}

build_profile <- function(horizons = c(5, 10, 15, 20, 25, 30)) {
  p <- .fit_profile(d, horizons)

  if (is.null(p)) {
    cat("  *** THE PROFILE TABLE WILL COMPILE BLANK, because it could not be\n",
        "      fitted. Every cell is written as \\tofill, which the manuscript\n",
        "      renders as red rules: a table that looks empty rather than\n",
        "      missing, which is why this has gone unnoticed twice.\n", sep = "")
    return(vapply(horizons, function(e)
      do.call(row_tex, c(list(e), as.list(rep(TOFILL, 4)))), character(1)))
  }
  cat("  profile fitted from the panel, ", nrow(p), " horizons.\n", sep = "")

  # Cross-check against the master's own fit when it is in the session.
  if (exists(".men_flex") && exists(".women_flex") &&
      exists(".exp_centre_m") && exists(".exp_centre_w") &&
      !is.null(get0(".men_flex")) && !is.null(get0(".women_flex"))) {
    dm <- max(abs(p$est_men - 100 * vapply(horizons, function(e)
      xpartial(get(".men_flex"), get(".exp_centre_m"), e), 0)))
    dw <- max(abs(p$est_women - 100 * vapply(horizons, function(e)
      xpartial(get(".women_flex"), get(".exp_centre_w"), e), 0)))
    if (max(dm, dw) > 0.1)
      cat("  *** this fit and the master's A5(iii) objects DISAGREE by up to ",
          sprintf("%.3f", max(dm, dw)), " points. The\n",
          "      specification has drifted between the two. The table below is\n",
          "      this file's fit; reconcile before using it.\n", sep = "")
    else
      cat("  cross-checked against the master's objects, agreeing to ",
          sprintf("%.3f", max(dm, dw)), " points.\n", sep = "")
  }

  vapply(seq_len(nrow(p)), function(i) {
    gp <- p$est_women[i] - p$est_men[i]
    sg <- sqrt(p$se_men[i]^2 + p$se_women[i]^2)
    row_tex(p$e[i],
            sprintf("%s (%s)", fmt(p$est_men[i]),   fmt(p$se_men[i], signed = FALSE)),
            sprintf("%s (%s)", fmt(p$est_women[i]), fmt(p$se_women[i], signed = FALSE)),
            fmt(gp),
            if (is.finite(gp) && is.finite(sg))
              sprintf("[%s, %s]", fmt(gp - 1.96 * sg), fmt(gp + 1.96 * sg))
            else TOFILL)
  }, character(1))
}


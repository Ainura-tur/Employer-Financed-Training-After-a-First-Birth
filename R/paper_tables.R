# The widened search, done once and kept. Only reached on a miss, where the
# answer "it is here" beats the answer "absent" every time.
.pt_find_wide <- function(name) {
  if (!exists(".wide", envir = .pt_csv_seen)) {
    .r <- if (!is.null(.pt_chr("PROJ_ROOT"))) PROJ_ROOT else getwd()
    cat("      widening the search under ", .r, " ...\n", sep = "")
    assign(".wide", list.files(.r, pattern = "[.]csv$", recursive = TRUE,
                               full.names = TRUE), envir = .pt_csv_seen)
  }
  w <- get(".wide", envir = .pt_csv_seen)
  w[basename(w) == name]
}

read_csv_if <- function(name) {
  hit <- PT_CSV_DIRS[file.exists(file.path(PT_CSV_DIRS, name))]

  if (!length(hit)) {
    cat(sprintf("  [missing] %s is in none of the %d folders above.\n",
                name, length(PT_CSV_DIRS)))
    .e <- .pt_find_wide(name)
    if (length(.e)) {
      cat("      *** IT EXISTS, OUTSIDE THE SEARCH PATH:\n")
      for (.f in .e)
        cat(sprintf("            %s   (%s)\n", .f,
                    format(file.info(.f)$mtime, "%Y-%m-%d %H:%M")))
      cat("      The writer and this reader disagree about which tree they are\n",
          "      in. Point OUTDIR at it or move the file. Do not copy it: a\n",
          "      second copy is the same problem one folder later.\n", sep = "")
    } else {
      cat("      Not anywhere under the project root either, so the stage that\n",
          "      writes it has not run in a session that wrote here.\n", sep = "")
    }
    cat("      Its cells are written as \\tofill, and write_body refuses the\n",
        "      write if a real fragment is already on disk. A fragment that\n",
        "      keeps its old timestamp after this line is that refusal, not a\n",
        "      table nobody generates.\n", sep = "")
    assign(name, NA_character_, envir = .pt_csv_seen)
    return(NULL)
  }

  # TWO COPIES IS A FINDING, NOT A TIE TO BREAK QUIETLY. Taking the first in
  # precedence order without saying so is how one file in two folders became a
  # week of work on the output side.
  if (length(hit) > 1) {
    .tags <- vapply(file.path(hit, name), function(q) {
      z <- utf8ToInt(paste(readLines(q, warn = FALSE), collapse = "\n"))
      sprintf("%08x", as.integer(sum(as.numeric(z) * seq_along(z)) %% 2^31))
    }, character(1))
    cat(sprintf("  *** %s exists in %d folders:\n", name, length(hit)))
    for (.j in seq_along(hit))
      cat(sprintf("        %s  %s  %s\n", .tags[.j],
                  format(file.info(file.path(hit[.j], name))$mtime,
                         "%Y-%m-%d %H:%M"), hit[.j]))
    if (length(unique(.tags)) == 1L)
      cat("      Identical bytes, so this is a copy and either will do.\n")
    else
      cat("      THE CONTENTS DIFFER. Taking the first in precedence order.\n",
          "      Pin or delete the other before quoting anything from this\n",
          "      table; a timestamp says when a file was written rather than\n",
          "      whether its numbers changed.\n", sep = "")
  }

  p <- file.path(hit[1], name)
  cat(sprintf("  [read] %s  from %s  (%s)\n", name, hit[1],
              format(file.info(p)$mtime, "%Y-%m-%d %H:%M")))
  assign(name, hit[1], envir = .pt_csv_seen)
  utils::read.csv(p, stringsAsFactors = FALSE)
}


# BUILDERS FOR TWO OF THE FOUR CARRIED TABLES
#
# A CARRIED TABLE IS WORSE THAN A MISSING ONE. It is written every run, so
# it always looks current, and no re-run can change it: the values came from
# the manuscript and no artefact is read to produce them. Two of the four
# are covered anyway because a verifier check reads their source
# independently, tab_training_main by Check 1 and tab_hours_arms by Check 6.
# The other two are typed and unverified, and that is the whole of the
# remaining gap.
#
# EACH BUILDER FALLS BACK RATHER THAN GUESSES. Column names in these two
# csvs were never fixed by a contract, so the resolver tries the plausible
# spellings and, when it cannot match, prints the names the file actually
# has and returns NULL. The carried block then writes as before. That way
# the first run either produces a real table or names the one line to
# change, and it can never quietly emit a table built from the wrong column.
.pick <- function(d, ...) {
  cand <- c(...)
  hit <- intersect(cand, names(d))
  if (length(hit)) hit[1] else NA_character_
}


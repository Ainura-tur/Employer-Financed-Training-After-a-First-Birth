  if (is.null(h) || !all(c("k", "female", "n", "p_t", "p_s") %in% names(h))) {
    cat("  *** ", FEE_HORIZON_CSV, " absent or missing columns, so\n",
        "      tab_fee_horizon is carried from the manuscript.\n", sep = "")
    return(NULL)
  }
  h$share <- ifelse(h$p_t > 0, 100 * h$p_s / h$p_t, NA_real_)
  ks <- sort(unique(h$k))
  g  <- function(kk, f, col) { v <- h[[col]][h$k == kk & h$female == f]
                               if (length(v)) v[1] else NA_real_ }
  num <- function(x, d) if (is.na(x)) TOFILL else formatC(x, format = "f", digits = d)
  out <- character(0)
  for (kk in ks) {
    # The rule the manuscript draws between the pre-birth block and k = 0.
    if (kk == 0 && length(out)) out <- c(out, "\\midrule")
    out <- c(out, row_tex(
      sprintf("$%s$", if (kk < 0) paste0("-", abs(kk)) else kk),
      num(g(kk, 0, "n"), 0), num(g(kk, 0, "p_t"), 3), num(g(kk, 0, "p_s"), 3),
      num(g(kk, 1, "n"), 0), num(g(kk, 1, "p_t"), 3), num(g(kk, 1, "p_s"), 3),
      num(g(kk, 0, "share"), 1), num(g(kk, 1, "share"), 1)))
  }
  cat("  fee horizon rebuilt from ", FEE_HORIZON_CSV, ": ", length(ks),
      " horizons.\n", sep = "")
  out
}


# v-mdemark, 19 October. SECTION 5.5'S RULE, IN ONE PLACE. A table marks an estimate
# that is significant at the 5 percent level (two-sided, normal) and smaller in
# magnitude than its own MDE, taken as 2.8 standard errors as the table notes
# say. Table 2 and Table D.1 both call below_mde(), so their marks follow the
# numbers and cannot drift from each other or from the text.
MDE_MARK_SE <- 2.8
below_mde <- function(est, se) {
  if (length(est) != 1L || length(se) != 1L || !is.finite(est) || !is.finite(se) || se <= 0)
    return(FALSE)
  2 * stats::pnorm(-abs(est / se)) < 0.05 && abs(est) < MDE_MARK_SE * se
}
# A math cell "$-0.064$" becomes "$-0.064^{a}$"; a plain cell gains "$^{a}$".
mde_mark <- function(cell, est, se, label = "") {
  if (identical(cell, TOFILL) || !below_mde(est, se)) return(cell)
  cat(sprintf("  below-MDE mark: %-52s %s (SE %s)\n", label, format(signif(est, 4)), format(signif(se, 3))))
  if (grepl("\\$$", cell)) sub("\\$$", "^{a}$", cell) else paste0(cell, "$^{a}$")
}


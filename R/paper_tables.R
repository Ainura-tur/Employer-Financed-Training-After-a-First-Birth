# Annual increments, reported by SEX rather than by parenthood because they
# are computed on consecutive wave pairs and the parenthood status can
# change between them.
# THE THRESHOLD IS THE RESULT, so it is named and its sensitivity is
# printed rather than buried. "Did the stock increase between consecutive
# waves" needs a cut, and the first draft used 0.01 years, which is 3.6
# days. An annual retrospective report cannot resolve that, so the cut was
# counting rounding noise as behaviour: it gave 11.2% for men against the
# 6.7% the paper carries, and nearly TRIPLED the unemployment rows.
#
# A quarter of a year is the smallest interval an annual recall can
# plausibly distinguish, and it is the default. The sensitivity table
# below shows what the choice costs, which is the only honest way to
# report a number that moves with an arbitrary cut.
# 0.50, not 0.25, and the sensitivity table is why.
#
# The draft table carried 6.7 / 17.0 (OLF) and 4.0 / 3.4 (unemployment).
# Those are the 0.50 row to the rounding: 6.69 / 17.03 / 4.02 / 3.45. So
# the original used a half-year cut and simply did not record it; the
# difference was never the sample or the definition.
#
# Half a year is the more conservative reading and it is defensible on its
# own terms: the stock is an annual recall in years and respondents
# plausibly round to halves, so 0.50 counts only increments large enough to
# survive that rounding. Keeping it also leaves the published figures
# unchanged, and moving to a LESS conservative cut would raise every rate
# while inviting a question about why.
INCREMENT_MIN <- 0.50

if (has("years_not_in_lf", "years_unemployed", "person_id", "wave")) {
  inc <- d %>% arrange(person_id, wave) %>% group_by(person_id) %>%
    mutate(d_olf   = years_not_in_lf   - dplyr::lag(years_not_in_lf),
           d_unemp = years_unemployed  - dplyr::lag(years_unemployed),
           gap     = wave - dplyr::lag(wave)) %>%
    ungroup() %>% filter(gap == 1)
  
  cat("\n  Increment threshold sensitivity (% with any increase):\n")
  sens <- do.call(rbind, lapply(c(0.01, 0.10, 0.25, 0.50, 0.90), function(th)
    inc %>% group_by(female) %>%
      summarise(threshold = th,
                olf   = 100 * mean(d_olf   > th, na.rm = TRUE),
                unemp = 100 * mean(d_unemp > th, na.rm = TRUE),
                .groups = "drop")))
  print(as.data.frame(sens), row.names = FALSE, digits = 3)
  cat(sprintf("  Using %.2f. A cut below about 0.25 counts rounding as\n",
              INCREMENT_MIN))
  cat("  behaviour: the stock is an annual recall in years.\n")
  cat("\n  The draft table carried 6.7 / 17.0 (OLF) and 4.0 / 3.4\n")
  cat("  (unemployment). If NO row above reproduces those, the difference\n")
  cat("  is not the threshold: check whether the older figures came from\n")
  cat("  the analysis sample rather than the broad one, or from a\n")
  cat("  different increment definition. Do NOT tune INCREMENT_MIN to hit\n")
  cat("  them; pick the defensible cut and report what it gives.\n")
  
  ii <- inc %>% group_by(female) %>%
    summarise(olf   = 100 * mean(d_olf   > INCREMENT_MIN, na.rm = TRUE),
              unemp = 100 * mean(d_unemp > INCREMENT_MIN, na.rm = TRUE),
              .groups = "drop")
  for (i in seq_len(nrow(ii))) {
    sx <- if (ii$female[i] == 1) "Women" else "Men"
    put(paste0("IncOlf", sx),   d1(ii$olf[i]),
        sprintf("annual OLF increment > %.2f yr, %%", INCREMENT_MIN))
    put(paste0("IncUnemp", sx), d1(ii$unemp[i]),
        sprintf("annual unemployment increment > %.2f yr, %%", INCREMENT_MIN))
  }
}


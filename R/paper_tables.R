  .in_b <- list.files(texdir, pattern = "[.]tex$")
  if (!length(.in_p)) {
    cat("\n  *** the paper's tables folder is empty. Nothing has synced.\n")
    return(invisible(FALSE))
  }
  .bad <- character(0)
  .tag <- function(q) {
    z <- utf8ToInt(paste(readLines(q, warn = FALSE), collapse = "\n"))
    sprintf("%08x", as.integer(sum(as.numeric(z) * seq_along(z)) %% 2^31))
  }
  .ph <- Filter(function(f)
    .pt_has_tofill(readLines(file.path(paper, f), warn = FALSE)), .in_p)
  if (length(.ph)) {
    cat(sprintf("\n  *** %d fragment(s) ON THE PAGE carry \\tofill:\n", length(.ph)))

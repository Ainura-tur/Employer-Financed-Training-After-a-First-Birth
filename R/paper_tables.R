# The paper reads four numbers off this table and every one is a claim about
# which arm carries the difference: mothers -0.124 at seven standard errors
# against fathers 0.001 at |t| 0.09, and on the workplace item -0.102 against
# +0.015 at |t| 1.06. "Ninety-nine per cent of the difference is the mothers'
# side" is a ratio of two cells in it, so a carried version is a ratio nobody

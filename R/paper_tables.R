#
# THE DIFFERENCE IS THE GAP COLUMN. It is formed within cohort-by-event
# cells and averaged on common cohort weights, as every women-minus-men
# estimate in the paper is, so it need not equal mothers less fathers. The
# typed column did; gap_separate in the csv is that subtraction.
#
# A value on a rounding boundary at three places prints to four, as the
# typed table did for mothers' own-time training at -0.0505.
.WS_ROWS <- list(
  list(block = "Workplace items, as estimated throughout",
       outcome = "jttpewt_any",           label = "Employer-financed training"),
  list(block = NULL, outcome = "jttpeot_any",           label = "Own-time training"),
  list(block = "All places, as drawn in Figures~\\ref{fig:ordering} and~\\ref{fig:whichside}",
       outcome = "training_paid_time",    label = "Paid-time training"),
  list(block = NULL, outcome = "training_own_time",     label = "Own-time training"),
  list(block = "Dosage",
       outcome = "total_courses_z",       label = "Courses"),
  list(block = NULL, outcome = "total_training_days_z", label = "Training days"))
.ws_num <- function(x) {
  if (length(x) != 1 || !is.finite(x)) return(TOFILL)
  r <- abs(x) * 1000 - floor(abs(x) * 1000)
  fmt(x, if (abs(r - 0.5) < 0.05) 4 else 3)
}
build_which_side <- function() {
  d <- read_csv_if("training_decomposition.csv")
  if (is.null(d)) return(NULL)
  .k  <- .pick(d, "k", "event_time")
  .ar <- .pick(d, "arm", "frame")
  .o  <- .pick(d, "outcome", "out", "series")
  .aw <- .pick(d, "mothers", "att_women", "att_w", "women")
  .sw <- .pick(d, "mothers_se", "se_women", "se_w")
  .am <- .pick(d, "fathers", "att_men", "att_m", "men")
  .sm <- .pick(d, "fathers_se", "se_men", "se_m")
  .g  <- .pick(d, "gap", "difference")
  .tw <- .pick(d, "mothers_t", "t_women")
  .tm <- .pick(d, "fathers_t", "t_men")
  .need <- c(k = .k, arm = .ar, outcome = .o, mothers = .aw, mothers_se = .sw,
             fathers = .am, fathers_se = .sm, gap = .g)
  if (anyNA(.need)) {
    cat("  *** tab_which_side: no builder run. Unmatched column(s): ",
        paste(names(.need)[is.na(.need)], collapse = ", "), "\n",
        "    the csv has: ", paste(names(d), collapse = ", "), "\n",
        "    The carried table, typed on 5 October, is written instead.\n",
        sep = "")
    return(NULL)
  }
  d <- d[is.finite(d[[.k]]) & d[[.k]] == 0 & d[[.ar]] == "employed_only", ,
         drop = FALSE]
  .miss <- setdiff(vapply(.WS_ROWS, `[[`, "", "outcome"), d[[.o]])
  if (!nrow(d) || length(.miss)) {
    cat("  *** tab_which_side: the decomposition csv lacks employed_only, k = 0",
        " row(s) for: ", paste(.miss, collapse = ", "),
        ". The carried table is written instead.\n", sep = "")
    return(NULL)
  }
  .t_of <- function(r, tc, ec, sc)
    abs(if (!is.na(tc) && is.finite(r[[tc]])) r[[tc]] else r[[ec]] / r[[sc]])
  out <- character(0)
  for (i in seq_along(.WS_ROWS)) {
    s <- .WS_ROWS[[i]]
    if (!is.null(s$block)) out <- c(out, if (i > 1) "\\addlinespace",
      sprintf("\\multicolumn{6}{l}{\\emph{%s}} \\\\", s$block))
    r <- d[d[[.o]] == s$outcome, , drop = FALSE][1, ]
    out <- c(out, row_tex(paste0("\\quad ", s$label),
      .ws_num(r[[.aw]]), fmt_plain(.t_of(r, .tw, .aw, .sw), 2),
      .ws_num(r[[.am]]), fmt_plain(.t_of(r, .tm, .am, .sm), 2),
      .ws_num(r[[.g]])))
  }
  .gs <- .pick(d, "gap_separate")
  if (!is.na(.gs)) {
    .dd <- d[[.g]] - d[[.gs]]
    cat(sprintf(paste0("  tab_which_side: built from training_decomposition.csv,",
                       " employed_only, k = 0. Common less separate weights on",
                       " the difference: %+.4f to %+.4f.\n"),
                min(.dd, na.rm = TRUE), max(.dd, na.rm = TRUE)))
  }
  out
}


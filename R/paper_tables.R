# the loader has put one there, and the change in experience_years
# otherwise. Event time is built as the left-censoring block builds it: a
# person not yet a parent in the first observed wave has k = 0 at the first
# wave as a parent, which gives the roster's transitioners.
#
# COMPARED, NOT TUNED. If the first run does not reproduce the typed values,
# they came from another frame or definition. Decide which to report; do not
# move the bucket edges until the numbers match.

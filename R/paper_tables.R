.stamp <- function(f) {
  if (!file.exists(f)) return(NA_character_)
  h <- tryCatch(readLines(f, n = 2, warn = FALSE), error = function(e) character(0))
  # Match on the content field where there is one, since build_tag names the
  # loader and the timestamp names the write. Content names the numbers, which
  # is what "is the paper reading this build" actually asks.
  h <- grep("content:|build_tag", h, value = TRUE)
  if (length(h)) trimws(sub("^%\\s*", "", h[1])) else "no stamp"
}

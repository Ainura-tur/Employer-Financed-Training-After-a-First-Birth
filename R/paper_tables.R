# Every fragment this file writes carries a build_tag line on line 2, so
# the two copies can be compared without parsing any LaTeX. Three states
# and they mean different things: MISSING is a fragment that never
# arrived, STALE is one the sync withheld and the paper is reading an
# older build of, and matching is the only clean one.

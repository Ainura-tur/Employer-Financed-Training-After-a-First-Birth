# v34. A FALLBACK DEFINITION IS NOT A PLACEHOLDER CELL.
#
# data_section_numbers.tex ends with \providecommand{\X}{\tofill} for every
# CamelCase control sequence the manuscript uses that this run did not write.
# That is a safety net, not a gap: it renders a red rule only where the name
# is otherwise undefined, and most of the list is LaTeX's own, \Delta and
# \Huge among them. The gate read those lines as placeholder cells and
# withheld the whole file, so sixty-eight macros stopped reaching the page and
# the manuscript went on compiling an older data section. The gate caused the
# failure it exists to prevent, and it did so quietly, once per run, in a line
# that reads like the gate working.
.pt_has_tofill <- function(lines) {
  .def <- grepl("\\\\(new|provide|renew)command\\s*\\{\\\\[A-Za-z]+\\}\\s*\\{\\\\tofill\\}",
                lines)
  any(grepl("tofill", lines[!.def], fixed = TRUE))
}


# v2. THE FRAGMENTS ARE BUILT INTO TEXDIR AND COPIED TO THE PAPER.
# TEXDIR is the contract's DIR_TABLES since v32; nothing here writes into the
# manuscript's own folder. sync_paper() withholds any fragment containing
# \tofill, so a partial build cannot reach the page silently.
# ---------------------------------------------------------------------
# v33. THE DELIVERY IS DEFINED HERE, so the gate does not depend on a file
# this project no longer sources. paths.R supplied sync_paper() and the
# contract does not; the branch below used to print "NOT copied to the paper"
# and carry on, which means the build and the page could drift apart for as
# long as nobody read that line. The rule is the same rule: a fragment
# carrying \tofill does not travel.
pt_sync_paper <- function(from = TEXDIR, to = PAPER_TABLES) {
  dir.create(to, showWarnings = FALSE, recursive = TRUE)
  .fr <- list.files(from, pattern = "[.]tex$")
  if (!length(.fr)) {
    cat("  sync: nothing to copy from ", from, "\n", sep = ""); return(invisible(FALSE))
  }
  .copied <- .same <- .held <- character(0)
  for (.f in .fr) {
    .src <- file.path(from, .f); .dst <- file.path(to, .f)
    if (.pt_has_tofill(readLines(.src, warn = FALSE))) {
      .held <- c(.held, .f); next
    }
    if (file.exists(.dst) && identical(readLines(.dst, warn = FALSE),
                                       readLines(.src, warn = FALSE))) {
      .same <- c(.same, .f); next
    }
    if (isTRUE(file.copy(.src, .dst, overwrite = TRUE))) .copied <- c(.copied, .f)
    else .held <- c(.held, paste0(.f, "  (COPY FAILED)"))
  }
  cat(sprintf("  sync to %s\n    %d copied, %d already current, %d withheld\n",
              to, length(.copied), length(.same), length(.held)))
  for (.f in .copied) cat("      -> ", .f, "\n", sep = "")
  if (length(.held)) {
    cat("    withheld, carries \\tofill:\n")
    for (.f in .held) cat("        ", .f, "\n", sep = "")
    cat("      The paper keeps its previous copy of each. Fix the input and\n",
        "      re-run rather than copying one across by hand: a placeholder on\n",
        "      the page is worse than a missing table, because it compiles.\n",
        sep = "")
  }
  invisible(!length(.held))
}

# v-which-side, 16 October (apply_paper_tables_pn_whichside.R). THE
# BUILDER READS THE COLUMNS MASTER WRITES. training_decomposition.csv
# (block 8.2b) carries arm, outcome, k, mothers, mothers_se, fathers,
# fathers_se, gap, gap_se, gap_separate, mothers_t and fathers_t. The
# resolver looked for att_women and att_men, so it never ran and the

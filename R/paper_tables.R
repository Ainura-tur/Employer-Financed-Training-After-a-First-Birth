# ONE DESTINATION. Briefly there were two, because the manuscript \input
# three of these with no prefix and five with tables/, so they resolved at
# different depths. The manuscript now uses tables/ for all eight and this
# writes them all to one folder, which is the same arrangement figures/ has
# and for the same reason: a paper's generated inputs should be collectable
# from one place.
#
# TEXDIR is beside the manuscript, not under project_dir. \input resolves
# relative to the .tex being compiled, and in this project the scripts and
# the manuscript sit in a subdirectory of the data root.
# A FRAGMENT IS A COMPLETE tabular, not a body of rows. The manuscript's
# floats supply the caption, label and notes and nothing else: the comment
# above \input{tables/app_b2_profile} says "the tabular, header row and
# column specification come from appendix_tables.R". Writing rows alone put
# an & outside any alignment and stopped the compile on the first fragment.
#
# So write_body takes the column spec and the header and wraps them here,
# once, rather than in five builders.
# A CONTENT TAG, because build_tag identifies the wrong thing. It is
# attr(d, "build_tag"), which names the LOADER build, so two fragments written
# by different versions of THIS file carry the same tag. On 4 September two
# descriptives tables sat on disk both stamped v21.43b, differing in every cell
# and in 1,079 person-waves, because one predated the in_wage_sample filter.
# Only the timestamp separated them, and a timestamp says when a file was
# written rather than whether its contents changed.
#
# Cheap and dependency-free: a positional checksum over the body. It is not a
# cryptographic hash and does not need to be. It has to answer one question,
# whether two fragments claiming to be the same table hold the same numbers.
#
# THE TAG IS NOT COMPARABLE ACROSS VERSIONS OF THIS FILE, because it hashes
# whatever scope this file passes it. The descriptive table's tag moved from
# 00856e8b to 066a234a between two runs four minutes apart whose output was
# byte-identical, because the scope widened from the cells to the whole
# fragment. That is the intended behaviour and it degrades in the safe
# direction: a paper copy written by an older generator reports STALE even
# when its numbers match, and a paper copy is from an older build in that
# case anyway. It will not report ok on a fragment that has changed.
.content_tag <- function(x) {
  z <- utf8ToInt(paste(x, collapse = "\n"))
  sprintf("%08x", as.integer(sum(as.numeric(z) * seq_along(z)) %% 2^31))
}

write_body <- function(rows, file, align, header = NULL, midrule = TRUE) {
  out <- c(sprintf("\\begin{tabular}{%s}", align), "\\toprule",
           if (!is.null(header)) header,
           if (!is.null(header) && midrule) "\\midrule",
           rows, "\\bottomrule", "\\end{tabular}")
  path <- file.path(TEXDIR, file)

  # v2. A PLACEHOLDER FRAGMENT DOES NOT OVERWRITE A REAL ONE.
  #
  # On 2 September this wrote app_b2_profile.tex with every cell set to
  # \tofill, because block A5(iii) of the master had not run in the session
  # and the flexible-profile objects were absent. Six rows of real estimates
  # were replaced by placeholders. The paper compiled, the table rendered
  # blank, and the driver's artefact report said "rebuilt", which was true and
  # useless. Nothing between the generator and the page could have caught it.
  #
  # The rule is narrow on purpose: refusing to write is only right when there
  # is something better already there. A first run with no previous fragment
  # SHOULD produce the \tofill version, because a table that compiles with
  # visible gaps is more useful than a missing \input. So the refusal applies
  # only when the existing file has content and the new one does not.
  # v32. ONE UNDEFINED CELL IS NOT A FAILED BUILD.
  #
  # The rule was "any placeholder in the new one and none in the old", which is
  # too coarse for a table with a cell that is undefined by construction.
  # tab_t2_profile.tex went unwritten through every run from 2:06 p.m. on 8
  # September onward, including runs where the csv was read and sixteen of its
  # seventeen rows were real: the d_gap cell at the earliest horizon was NA
  # because a first difference has no predecessor there, one placeholder
  # against a legacy copy with none, and the refusal fired. It would have gone
  # on firing forever, and no message said the input had been found.
  #
  # A fragment with real rows in it is not worse than an older file. The
  # refusal now applies where it was aimed: EVERY row a placeholder, which is
  # what an absent input produces, against an existing file that has values.
  # A partial build is written and names the rows that are short.
  .bad_rows <- grep("tofill", rows, fixed = TRUE)
  .new_bad  <- .pt_has_tofill(out)
  .all_bad  <- length(rows) > 0L && length(.bad_rows) == length(rows)
  .old_ok   <- file.exists(path) &&
    !.pt_has_tofill(readLines(path, warn = FALSE))

  if (length(.bad_rows) && !.all_bad) {
    cat(sprintf(paste0("  %d of %d body row(s) of %s carry a placeholder. The",
                       " input exists\n      and holds a non-finite value, so",
                       " check those columns rather than\n      re-running the",
                       " upstream stage. Written anyway; sync_paper() will\n",
                       "      withhold it until they are real.\n"),
                length(.bad_rows), length(rows), file))
    for (.r in utils::head(.bad_rows, 3))
      cat("        row ", .r, ": ", substr(rows[.r], 1, 92), "\n", sep = "")
    rm(.r)
  }

  if (.all_bad && .old_ok) {
    cat(sprintf(paste0("  *** NOT WRITTEN: %s would replace real values with",
                       " \\tofill.\n      EVERY row is a placeholder, so the",
                       " input was absent or unreadable\n      rather than",
                       " incomplete. The existing fragment is kept. Run the\n",
                       "      stage that supplies its inputs, then re-run",
                       " this one.\n"), file))
    return(invisible(FALSE))
  }
  # A BARE UNDERSCORE IN A WRITTEN FRAGMENT IS ALWAYS A BUG, and this has now
  # halted the build three times running: hourly_wage_clean from the T0b csv,
  # jttpewt_obs beside it, and "(no title in LEDGER_PANELS)" from a fallback
  # string in this very file. Each was found by LaTeX rather than by R, one
  # per compile, which is the slowest possible way to find three instances of
  # one mistake.
  #
  # So the class is checked here rather than the instances upstream. Math is
  # stripped first, since $k$ and $-0.116$ are fine and common, and escaped
  # underscores with it. What remains is a name that reached a table without
  # passing through an escape, and the message names the line so the fix goes
  # into the builder rather than into the fragment.
  .chk <- gsub("\\$[^$]*\\$", "", gsub("\\\\_", "", out))
  .bad_us <- grep("_", .chk, fixed = TRUE)
  if (length(.bad_us)) {
    cat("  *** ", length(.bad_us), " line(s) of ", file, " carry a bare\n",
        "      underscore outside math. LaTeX stops at 'Missing $ inserted'.\n",
        "      Escape it in the builder, not in the fragment:\n", sep = "")
    for (.i in head(.bad_us, 4))
      cat("        ", substr(out[.i], 1, 72), "\n", sep = "")
    rm(.i)
  }
  rm(.chk, .bad_us)

  # The fragments written here carried no stamp at all, so the arrival audit
  # at the foot of this file could see one fragment out of ten. Two lines,
  # matching the descriptive table's header, and every fragment becomes
  # checkable against the copy the paper is reading.
  writeLines(c("% Generated by paper_tables.R. Do not edit by hand.",
               paste0("% ", format(Sys.time(), "%Y-%m-%d %H:%M"),
                      "  build_tag: ", if (exists("bt") && !is.null(bt)) bt else "ABSENT",
                      "  content: ", .content_tag(out)),
               out), path)
  cat(sprintf("  wrote %s (%d rows, content %s)%s\n", path, length(rows),
              .content_tag(out),
              if (.new_bad) "  *** CONTAINS \\tofill, do not sync" else ""))
  invisible(TRUE)
}


    cat("      These reached the manuscript around the gate, by hand or from a\n",
        "      run where the build folder and this one were the same.\n", sep = "")
    .bad <- c(.bad, .ph)
  }
  .stale <- Filter(function(f)
    !identical(.tag(file.path(paper, f)), .tag(file.path(texdir, f))),
    intersect(.in_p, .in_b))
  if (length(.stale)) {
    cat(sprintf("\n  *** %d fragment(s) differ from the build:\n", length(.stale)))
    for (f in .stale)
      cat(sprintf("        %s   build %s   page %s\n", f,
                  .tag(file.path(texdir, f)), .tag(file.path(paper, f))))
    cat("      Withheld by the gate, or synced from an older run. The page is\n",
        "      compiling against numbers this build did not produce.\n", sep = "")
    .bad <- c(.bad, .stale)
  }
  .orph <- setdiff(.in_p, .in_b)
  if (length(.orph)) {
    cat(sprintf("\n  *** %d fragment(s) on the page have no generator:\n",
                length(.orph)))
    for (f in .orph) cat("        ", f, "\n", sep = "")
    cat("      Nothing in the build folder writes these. Typed, or left by a\n",
        "      retired script. A typed table is the defect tab_t2_profile was.\n",
        sep = "")
    .bad <- c(.bad, .orph)
  }
  if (!length(.bad))
    cat(sprintf("\n  gate ok: %d fragment(s), none with \\tofill, all matching the build.\n",
                length(.in_p)))
  invisible(!length(.bad))
}

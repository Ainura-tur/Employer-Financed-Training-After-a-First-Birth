    # IT IS A FRAME, NOT A VINTAGE. The 2 September run settled this. The
    # shares here came out at 77.7 and 78.1 against the diagnostic's 88.0
    # and 88.4, and the GAIN matched at 0.4, which is the birth item's
    # signature; on the pregnancy item the gain is 16.0. Same item,
    # different level, so the two differ in the population the share is
    # taken over and not in which question they read.
    #
    # AND THIS FILE ALREADY KNEW. Twenty lines above, the transitions are
    # withheld from the macro file on the ground that this file computes
    # them on the whole panel while the master computes them on the
    # analysis sample, and that emitting them would create a second source
    # that can quietly disagree. The validation shares are computed from
    # that same full-panel object and were emitted anyway, which is the
    # rule being broken two statements after it is stated. Deferring below
    # repairs it; the diagnostic owns the analysis-sample share.
    # THE KEYS ARE MATCHED, NOT SPELLED. A hard-coded key name that has
    # been renamed upstream fails the same way a missing file does, and
    # then this block quietly emits its own value again, which is the
    # failure it exists to prevent. Rows are matched on a pattern and the
    # names actually used are printed, so a rename shows up as a changed
    # key rather than as a silent fallback. Anything mentioning the
    # pregnancy item is excluded outright: it is the wrong item here, not
    # a second opinion on the right one.
    .hf <- read_csv_if("headline_figures.csv")
    .owned <- NULL
    # The writer, Pre_analysis_diagnostics2.R ITEM 12, emits a wide table:
    # one row per window and sample, with the shares as columns. Take the
    # birth-item columns from the 20-55 rows; they repeat across samples.
    if (!is.null(.hf) &&
        all(c("window", "pct_birth_same", "pct_birth_window") %in% names(.hf))) {
      .w <- .hf[.hf$window == "20-55", , drop = FALSE]
      if (nrow(.w)) {
        .owned <- c(same = as.numeric(.w$pct_birth_same[1]),
                    two  = as.numeric(.w$pct_birth_window[1]))
        .kn <- c("pct_birth_same (20-55)", "pct_birth_window (20-55)")
        cat("  headline_figures columns used: ",
            paste(.kn, collapse = ", "), "\n", sep = "")
      }
      rm(.w)
    }
    .kn <- c(NA_character_, NA_character_)
    if (is.null(.owned) && !is.null(.hf)) {
      .kc <- intersect(c("key", "name", "item", "figure"), names(.hf))[1]
      .vc <- intersect(c("value", "val", "x"), names(.hf))[1]
      if (!is.na(.kc) && !is.na(.vc)) {
        .k <- as.character(.hf[[.kc]])
        .ok <- grepl("valid", .k, ignore.case = TRUE) &
          !grepl("preg|leprg", .k, ignore.case = TRUE)
        .pick <- function(pat) {
          i <- which(.ok & grepl(pat, .k, ignore.case = TRUE))
          if (!length(i)) return(c(NA_real_, NA_character_))
          c(suppressWarnings(as.numeric(.hf[[.vc]][i[1]])), .k[i[1]])
        }
        .a <- .pick("same"); .b <- .pick("two|wide|window")
        .owned <- c(same = as.numeric(.a[1]), two = as.numeric(.b[1]))
        .kn <- c(.a[2], .b[2])
        cat("  headline_figures keys used: ",
            paste(ifelse(is.na(.kn), "none", .kn), collapse = ", "), "\n", sep = "")
        rm(.k, .ok, .pick, .a, .b)
      }
      rm(.kc, .vc)
    }
    if (!is.null(.owned) && all(is.finite(.owned))) {
      .gap <- max(abs(c(.v_same - .owned[["same"]], .v_two - .owned[["two"]])))
      cat(sprintf(paste0("  validation: here %.1f/%.1f, headline_figures ",
                         "%.1f/%.1f, largest gap %.1f points\n"),
                  .v_same, .v_two, .owned[["same"]], .owned[["two"]], .gap))
      # v31. EQUAL GAPS MEAN ONE DENOMINATOR, AND THIS FILE'S VALUES WIN.
      #
      # The deferral rule is that the script computing a quantity for its
      # own sake outranks the one computing it in passing, and that is
      # right whenever the two are answering the same question. Here they
      # are not. ITEM 12 takes the match rate over the 2,388 transitions
      # where the life-event item is OBSERVED and gets 88.0 and 88.4; this
      # file takes it over all 2,704, counting an unobserved item as
      # unmatched, and gets 77.7 and 78.1. Same item, same waves, one
      # denominator apart.
      #
      # THE TELL IS THAT BOTH GAPS ARE THE SAME. A denominator change
      # scales both shares by the observation rate, 0.8831, so it moves
      # them by 10.3 points each; a different ITEM, or a stale build,
      # moves them by different amounts. That is a discriminator the
      # pregnancy warning below already relies on in the other direction.
      #
      # AND THE UNCONDITIONAL FIGURE IS THE ONE THE PAPER MEANS. A claim
      # that the absorbing transition is childbirth in X per cent of cases
      # is a claim about all transitions, and a transition whose item is
      # missing is not a verified birth. Deferring here would substitute a
      # permissive figure for a conservative one and call it a correction.
      .same_denom <- .gap > 0.5 &&
        abs((.owned[["same"]] - .v_same) - (.owned[["two"]] - .v_two)) < 0.2 &&
        .owned[["same"]] > .v_same
      if (.same_denom) {
        cat(sprintf(paste0("  *** ONE DENOMINATOR, NOT TWO ANSWERS. Both shares",
                           " differ by %.1f points,\n      which is the",
                           " signature of a denominator change rather than a",
                           "\n      different item or a stale build. The",
                           " diagnostic conditions on the\n      life-event",
                           " item being observed; this file does not, and the",
                           "\n      paper's claim is about ALL transitions.",
                           " KEEPING this file's\n      %.1f/%.1f. Report the",
                           " diagnostic's %.1f/%.1f beside them with its\n",
                           "      own denominator named.\n"),
                    .owned[["same"]] - .v_same, .v_same, .v_two,
                    .owned[["same"]], .owned[["two"]]))
      } else {
        if (.gap > 0.5) {
          cat("  *** THESE DISAGREE. The diagnostic is authoritative and its\n",
              "      values are emitted. Before accepting them, check which\n",
              "      item each side resolved: a gap near 13 points on the\n",
              "      same-wave share with the two-wave share ABOVE it is the\n",
              "      pregnancy item, not a stale build.\n", sep = "")
        }
        .v_same <- .owned[["same"]]; .v_two <- .owned[["two"]]
        cat("  emitting the diagnostic's values, from keys above.\n")
      }
      rm(.same_denom)
    } else {
      cat("  validation: headline_figures.csv unavailable or missing the\n",
          "  two keys, so the values below are this file's own and are\n",
          "  NOT cross-checked against the diagnostic that owns them.\n",
          sep = "")
    }
    put("ValidTwoWave", pct(.v_two),
        "transition coincides with a reported birth, two-wave window")
    put("ValidSameWave", pct(.v_same), "same wave only")
    put("ValidWindowGain", pct(.v_two - .v_same),
        "what widening the window buys on the birth item; footnote 5")
    rm(.v_same, .v_two, .hf, .owned, .kn)
  } else cat("  birth event column unavailable; validation skipped\n")
}

# Contamination: women who look childless on a current-children definition
# but are ever-parents on the absorbing one.
# THE COMPARATOR IS group_3way_women, and the counts settle it.
#
# The question was which current-children measure the "standard definition"
# should be taken to be, since resident-children-only, all own children, and
# children-under-15 give materially different answers. An earlier version of
# this block used num_own_resident_children == 0 and returned 18.4%, against
# the 35.7% the draft carried, and the gap looked like a build difference.
#
# It was a denominator. The three-way split gives never_mothers 24,727 and
# post_mothers 13,733, so post-mothers are 13,733 / 38,460 = 35.7% of women
# who look childless on a current-children measure. That reproduces the
# published figure exactly, so the comparator is the absorbing definition's
# own three-way split rather than any household-roster count.
#
# This is also the right comparator on its own terms: post_mother means a
# woman who WAS a mother and whose children have aged out, which is exactly
# the group a current-children measure misclassifies. A resident-children
# count answers a related but different question, and answering the wrong
# one to three significant figures is worse than not answering it.
# v2. PRE-MOTHERS BELONG IN THE DENOMINATOR, and on this build they are no
# longer inside never_mothers. group_3way_women now carries a pre_mothers
# level of its own: the 23 September run crosstabs it one-to-one against
# group_4way_women_life, 6,242 person-waves that the old denominator
# swept up with the never-mothers and the new one dropped on the floor.
#
# The claim is a share of the women a current-children measure reads as
# childless. That measure reads a woman as childless whenever no child
# under 15 lives with her, which is true of never-mothers, of mothers
# before their first birth, and of post-mothers alike. Leaving pre-mothers
# out shrinks the denominator and inflates the share: 11,567 over 29,806
# is 38.8 per cent, and 11,567 over 36,048 is 32.1.

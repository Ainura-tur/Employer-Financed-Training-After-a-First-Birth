# people contributes waves to two columns.
#
# WHY IT MATTERS FOR THIS TABLE SPECIFICALLY. `Since`, years since leaving
# education, is a career-length measure. The NeverMothers arm holds
# mothers-to-be's YOUNG pre-birth waves and the Mothers arm holds only their
# OLDER post-birth ones, so part of the gap between those two columns is the
# grouping rather than the biology. The same mechanism inflates the OLF
# contrast. The claim the table carries - childless men and childless women
# alike, fathers no different, mothers apart - survives, because both
# childless arms are contaminated the same way and the comparison between
# them is fair. The mothers-against-never-mothers contrast is partly a

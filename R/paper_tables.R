# within a person, and "_ever" reads as though it were.
#
# So the four arms contain:
#   Mothers        post-birth waves ONLY
#   NeverMothers   true never-mothers PLUS every mother-to-be's pre-birth waves
#   Fathers        post-birth waves only
#   ChildlessMen   true childless men PLUS every father-to-be's pre-birth waves
#
# The arms partition person-WAVES exactly - they sum to the panel - which is
# why nothing ever looked wrong. They do not partition PERSONS: the panel

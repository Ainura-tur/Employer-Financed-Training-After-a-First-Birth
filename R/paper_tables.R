# ---- one builder, called twice ------------------------------------------
# frame is the person-waves; assign_col labels them; anything labelled but
# not in cols is held out ON PURPOSE and counted, which is the difference
# between a column left out and a column lost. wage_row adds a third count
# row for a frame whose rows do not share a denominator.
.make_desc <- function(frame, assign_col, cols, out, caption, label, notes,
                       wage_row = FALSE) {
  dt <- frame
  dt$col <- assign_col(dt)
  .na <- sum(is.na(dt$col))
  if (.na)
    cat(sprintf("  %s: %s person-wave(s) unassigned to any column.\n",
                basename(out), n_fmt(.na)))
  .off <- !is.na(dt$col) & !(dt$col %in% cols)
  if (any(.off))
    cat(sprintf("  %s: %s person-wave(s) held out by design (%s).\n",
                basename(out), n_fmt(sum(.off)),
                paste(sort(unique(dt$col[.off])), collapse = ", ")))
  dt <- dt[!is.na(dt$col) & dt$col %in% cols, , drop = FALSE]
  for (.cl in cols)
    if (!sum(dt$col == .cl))
      warning("descriptive table: column \"", .cl, "\" is empty. It will ",
              "render as dashes with a count of zero, which reads as a data ",
              "problem rather than a matching error.", call. = FALSE)

  # Rows. Each is name, column, formatter. A variable absent from the panel
  # is DROPPED with a printed note rather than rendered as a row of dashes:
  # a dash reads as "measured and zero" to anyone who did not run this.
  .rows <- list(
    list("Age",                        "age",                  d1),
    list("Years of education",         "educ_years",           d1),
    list("Experience (years)",         "experience_years",     d1),
    list("Hourly wage (\\$)",           NA,                     d2),
    list("Weekly hours",               "hours_worked_clean",   d1),
    list("Full time (\\%)",             "fulltime",             function(x) d1(100*x)),
    list("Employer-financed training (\\%)", NA,                  function(x) d1(100*x)),
    list("Own-time training (\\%)",     NA,                     function(x) d1(100*x)),
    list("Partnered (\\%)",             "married",              function(x) d1(100*x)))
  .rows[[4]][[2]] <- intersect(c("hourly_wage_clean","hourly_wage"), names(dt))[1]
  .rows[[7]][[2]] <- intersect(c("jttpewt_obs","jttpewt_any",
                                 "training_paid_time_obs"), names(dt))[1]
  .rows[[8]][[2]] <- intersect(c("jttpeot_any","training_own_time_obs",
                                 "training_own_time"), names(dt))[1]
  .keep <- vapply(.rows, function(r) !is.na(r[[2]]) && r[[2]] %in% names(dt),
                  logical(1))
  if (any(!.keep))
    cat("  rows dropped, variable not on this panel: ",
        paste(vapply(.rows[!.keep], function(r) r[[1]], ""), collapse = ", "),
        "\n", sep = "")
  .rows <- .rows[.keep]

  .cell <- function(v, fun, cl) {
    x <- dt[[v]][dt$col == cl]
    x <- x[is.finite(x)]
    if (!length(x)) "--" else fun(mean(x))
  }
  body <- vapply(.rows, function(r)
    paste0(r[[1]], " & ",
           paste(vapply(cols, function(cl) .cell(r[[2]], r[[3]], cl), ""),
                 collapse = " & "), " \\\\"),
    character(1))
  ns  <- vapply(cols, function(cl) n_fmt(sum(dt$col == cl)), "")
  nps <- vapply(cols, function(cl)
    n_fmt(dplyr::n_distinct(dt$person_id[dt$col == cl])), "")
  nws <- if (wage_row && "in_wage_sample" %in% names(dt))
    vapply(cols, function(cl)
      n_fmt(sum(dt$col == cl & dt$in_wage_sample == 1, na.rm = TRUE)), "") else NULL

  # THE TAG COVERS THE WHOLE FRAGMENT, not just the cells. Hashing body, ns
  # and nps alone would leave the caption, the column headers and the note
  # outside it, and a note that no longer describes the table it sits under
  # is the failure this file has already had once: the note said "means over
  # the wage sample" while the fragment was on a wider frame.
  .frag <- c(
    "\\begin{table}[htbp]",
    "\\centering",
    paste0("\\caption{", caption, "}"),
    paste0("\\label{", label, "}"),
    "\\begin{threeparttable}",
    if (length(cols) >= 6) "\\footnotesize" else "\\small",
    paste0("\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}l",
           strrep("c", length(cols)), "}"),
    "\\toprule",
    paste0(" & ", paste(cols, collapse = " & "), " \\\\"),
    "\\midrule",
    body,
    "\\addlinespace",
    paste0("\\textit{Person-waves} & ", paste(ns,  collapse = " & "), " \\\\"),
    paste0("\\textit{Persons} & ",      paste(nps, collapse = " & "), " \\\\"),
    if (!is.null(nws))
      paste0("\\textit{Of which, wage sample} & ", paste(nws, collapse = " & "),
             " \\\\") else NULL,
    "\\bottomrule",
    "\\end{tabular*}",
    "\\begin{tablenotes}[flushleft]",
    "\\small",
    notes,
    "\\end{tablenotes}",
    "\\end{threeparttable}",
    "\\end{table}")

  writeLines(c(
    "% Generated by paper_tables.R. Do not edit by hand.",
    paste0("% ", format(Sys.time(), "%Y-%m-%d %H:%M"), "  content: ",
           .content_tag(.frag), "  build_tag: ",
           if (is.null(bt)) "ABSENT" else bt),
    .frag), out)
  cat("  wrote ", out, ": ", length(.rows), " rows x ", length(cols),
      " columns, content ", .content_tag(.frag), "\n", sep = "")
  invisible(out)
}


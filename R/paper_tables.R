fmt_signed <- function(x, digits = 3) {
  if (length(x) != 1 || !is.finite(x)) return(TOFILL)
  s <- formatC(abs(x), format = "f", digits = digits)
  if (x < 0) paste0("$-$", s) else paste0(" ", s)
}

